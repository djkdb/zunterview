#!/usr/bin/env node
/**
 * Merges researched company interview data (research/raw/*.json) into
 * shared/data/companies.ts. Cleans text, drops malformed entries and
 * near-duplicate questions, and reports what it did.
 *
 *   node scripts/build-company-data.mjs
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const RAW = "research/raw";
const OUT = "shared/data/companies.ts";
// Question banks are served on demand (public/data/companies/<id>.json) so they stay out of the app bundle.
const Q_DIR = "public/data/companies";
const Q_CATEGORIES = new Set(["인성", "직무", "경험", "상황", "기업이해", "PT·토론", "기술"]);
const CATEGORY_ALIASES = { PT: "PT·토론", 토론: "PT·토론", "PT/토론": "PT·토론", 기업: "기업이해", 지원동기: "기업이해" };

const clean = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
const grams = (s) => {
  const t = s.toLowerCase().replace(/[\s"'“”‘’.,!?…·:;()[\]{}\-_/]+/g, "");
  const out = new Set();
  for (let i = 0; i < t.length - 1; i++) out.add(t.slice(i, i + 2));
  return out;
};
const sim = (a, b) => {
  const A = grams(a), B = grams(b);
  if (!A.size || !B.size) return 0;
  let n = 0;
  for (const g of A) if (B.has(g)) n++;
  return n / (A.size + B.size - n);
};

const curation = JSON.parse(readFileSync("research/curation.json", "utf8"));
const companies = [];
const report = [];
for (const file of readdirSync(RAW).filter((f) => f.endsWith(".json")).sort()) {
  const data = JSON.parse(readFileSync(join(RAW, file), "utf8"));
  for (const c of data.companies ?? []) {
    const questions = [];
    let dropped = 0;
    for (const q of c.questions ?? []) {
      const text = clean(q.text);
      const category = CATEGORY_ALIASES[clean(q.category)] ?? clean(q.category);
      if (curation.dropQuestions.some((d) => d.id === c.id && clean(d.text) === text)) {
        dropped++;
        continue;
      }
      const override = curation.reclassify.find((r) => r.id === c.id && (!r.category || r.category === category) && (!r.text || clean(r.text) === text));
      const basis = override ? override.basis : clean(q.basis) === "후기" ? "후기" : "공식자료";
      if (text.length < 4 || text.length > 140 || !Q_CATEGORIES.has(category) || questions.some((x) => sim(x.text, text) >= 0.6)) {
        dropped++;
        continue;
      }
      questions.push({ text, category, track: clean(q.track) || "공통", basis });
    }
    const sources = (c.sources ?? [])
      .map((s) => ({ title: clean(s.title).slice(0, 200), url: clean(s.url) }))
      .filter((s) => /^https?:\/\//.test(s.url))
      .filter((s) => !curation.dropSources.some((d) => d.id === c.id && s.url.includes(d.urlIncludes)))
      .filter((s) => !(curation.dropSourcesEverywhere ?? []).some((d) => s.url.includes(d)))
      .filter((s, i, arr) => arr.findIndex((x) => x.url === s.url) === i)
      .slice(0, 20);
    if (questions.length < 5 || !sources.length) {
      report.push(`SKIP ${c.name}: ${questions.length} questions, ${sources.length} sources`);
      continue;
    }
    companies.push({
      id: clean(c.id),
      name: clean(c.name),
      ...(c.shortName ? { shortName: clean(c.shortName).slice(0, 20) } : {}),
      category: clean(c.category),
      industry: clean(c.industry).slice(0, 60),
      talent: (c.talent ?? []).map(clean).filter(Boolean).map((t) => t.slice(0, 100)).slice(0, 12),
      process: (c.process ?? []).map(clean).filter(Boolean).slice(0, 8),
      style: clean(c.style).slice(0, 400),
      tips: (c.tips ?? []).map(clean).filter(Boolean).slice(0, 8),
      questions: questions.slice(0, 150),
      sources,
    });
    report.push(`${c.name}: ${questions.length} questions (${questions.filter((q) => q.basis === "후기").length} reported)${dropped ? `, ${dropped} dropped` : ""}, ${sources.length} sources`);
  }
}

rmSync(Q_DIR, { recursive: true, force: true });
mkdirSync(Q_DIR, { recursive: true });
for (const c of companies) writeFileSync(join(Q_DIR, `${c.id}.json`), `${JSON.stringify({ questions: c.questions })}\n`);
const profiles = companies.map(({ questions, ...c }) => ({
  ...c,
  questionCount: questions.length,
  reportedCount: questions.filter((q) => q.basis === "후기").length,
  tracks: [...new Set(questions.map((q) => q.track).filter((t) => t !== "공통"))],
}));
writeFileSync(
  OUT,
  `// Generated by scripts/build-company-data.mjs from research/raw/*.json — do not edit by hand.\n` +
    `// Compiled from public interview reviews and official recruiting pages. Questions: public/data/companies/<id>.json\n` +
    `export const COMPANY_DATA: unknown[] = ${JSON.stringify(profiles, null, 1)};\n`,
);
console.log(report.join("\n"));
console.log(`\n${companies.length} organizations, ${companies.reduce((s, c) => s + c.questions.length, 0)} questions → ${OUT}, ${Q_DIR}/*.json`);
